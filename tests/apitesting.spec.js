import {test,expect} from "@playwright/test";

//GET REQUEST
test.only('@api GET request - fetch users', async({request})=>{ //Tagging for grouping - @api

const response = await request.get('https://jsonplaceholder.typicode.com/users');
expect(response.ok()).toBeTruthy(); //validation - 2xx-lulla ethenkilum oru response aano 
//kittiyittulathu
//toBeTruthy = will check will all 1xx,2xx,3xx,4xx,5xx response status codes. 
const body = await response.json();
console.log(body);

expect(body.length).toBeGreaterThan(0); //Checking content

});

//POST REQUEST
test('@api POST request - Create User',  async ({request})=>{ //Tagging for grouping - @api

    const response = await request.post('https://jsonplaceholder.typicode.com/users' , {

        data: { //JSON Object and data is a keyword
            name: 'John Doe',
            email: 'john@example.com'
        }


    });

    //Validate status code
    expect(response.status()).toBe(201); //201 - Created successfully, njan specific aayi code 
    //number kodukkunnu
    
    //expect(response.ok()).toBeTruthy(); //Eee code step-um enikku kodukkam here like in get request
    //but the response status code is from 200 to 299, ethil ethu vannalum toBeTruthy true aakum
    
    //Validate response body
    const responseBody = await response.json();
    console.log(responseBody);
    console.log('Status code: ', response.status()); //Printing the status code
    expect(responseBody.name).toBe('John Doe'); //post method success aayi ennu orapikkam

    //Output-il id autogenerated aanu.
});

//PATCH Request - Partial update
test('PATCH request - update user', async ({request})=>{
    const response = await request.patch('https://jsonplaceholder.typicode.com/users/1',{

data: {
    email: 'updatedjohn@example.com'
}

    });

    expect(response.status()).toBe(200); //201 is also fine in patch request, but 203, 204 status code
    //varukayanenkil athonnum valid aayi kanakakkathilla.

    const responseBody = await response.json();
    console.log(responseBody);
    expect(responseBody.email).toBe('updatedjohn@example.com');

});

//PUT REQUEST:- Full update
